# A question mark, exclamation point, or period (that isn't part of an ellipse), followed by optional quotations, followed by a newline
SEGMENT_END = re.compile(r"(\?|\!|(?<!\.\.)\.)" + "(\"|\')*$")

assert     SEGMENT_END.search("I end with an exclamation point!")
assert     SEGMENT_END.search("\"I end with an exclamation point!\"")
assert     SEGMENT_END.search("\'I end with an exclamation point!\'")
assert     SEGMENT_END.search("I end with a period.")
assert     SEGMENT_END.search("I end with a question mark?")
assert not SEGMENT_END.search("I end with a an ellipse...")

def regex_segment(rows: Iterable[Any]) -> Generator[Any, None, None]:
    subrows = []
    for row in rows:
        subrows.append(row)
        if SEGMENT_END.search(row['text']):
            yield {
                "text": ''.join([sub['text'] for sub in subrows]),
                "start": subrows[0]['start'],
                "end": subrows[-1]['end']
            }
            subrows = []
    if subrows:
        yield {
                "text": ''.join([sub['text'] for sub in subrows]),
                "start": subrows[0]['start'],
                "end": subrows[-1]['end']
            }

